def test_simulate_weights_rejects_unpriced_risk_asset(tmp_path: Path) -> None:
    """A positive weight on a configured-but-unpriced asset is an error."""
    settings, prices, _, _ = _regression_inputs(tmp_path)
    settings = settings.model_copy(
        update={
            "data": settings.data.model_copy(
                update={"risk_assets": (*settings.data.risk_assets, "DBC")},
            ),
        },
    )

    decisions = pd.DataFrame({"SPY": [0.5], "DBC": [0.5]}, index=prices.index[:1])
    with pytest.raises(ValueError, match="no prices"):
        simulate_weights(prices, decisions, settings)

    # A zero weight on the unpriced asset is tolerated -- the column is dropped.
    zero = pd.DataFrame({"SPY": [0.5], "DBC": [0.0]}, index=prices.index[:1])
    result = simulate_weights(prices, zero, settings)
    assert "DBC" not in result.held_weights.columns
